@Composable
fun PathIcon(pathData: String, tint: Color, size: Dp = 24.dp, modifier: Modifier = Modifier) {
    val path = remember(pathData) { PathParser.createPathFromPathData(pathData).asComposePath() }
    Canvas(modifier.size(size)) {
        val s = size.toPx() / 24f
        scale(s) { drawPath(path, tint) }
    }
}

@Composable
fun IconTap(
    path: String,
    tint: Color,
    size: Dp = 24.dp,
    pad: Dp = 8.dp,
    onClick: () -> Unit
) {
    Box(
        Modifier
            .clip(RoundedCornerShape(12.dp))
            .clickable(onClick = onClick)
            .padding(pad)
    ) { PathIcon(path, tint, size) }
}
